// A random walk on real state for the Percolator v16 port's TradeNoCpi (showcase/mainnet/percolator-v16/trading.ts),
// against the reference: Percolator v16 at commit 7b110913 (engine 5e3af07), aeyakovenko/percolator-prog and
// aeyakovenko/percolator, Apache-2.0; test/programs/percolator_v16.so, the Rust build of those commits, not a deployed
// program. Every transaction is compared whole at every step (outcome, logs, inner instructions, return data, every
// named account's bytes; fewer compute units on success).
//
// The world: a market of three assets (AuthMark, EwmaMark, and a hybrid on the world's external oracles) with funding
// enabled, four funded portfolios, and a Clock that moves. Legs are opened by trades, so the settlement of open legs, the
// funding accrual, the refresh and the health certificates run on state the instructions themselves made, not on
// generated bytes. Steps: trades between two portfolios (sizes from one unit to near the position cap, prints near the
// mark and at the bounds, fees from zero to the cap, a tenth with mutated data or accounts), mark pushes and
// reconfigurations that move the stored targets and the funding marks, the hybrid's oracle accounts refreshed with
// moving prices, maintenance-fee syncs, deposits, withdrawals (which need flat portfolios), lifecycle changes of asset 1
// while legs are open (drain-only, shutdown, retire, reactivation), policy updates. The low marks (about 100 e6) keep the
// per-slot price cap below one unit for a few slots, so the zero-move funding path accrues funding on a balanced asset
// whose stored mark differs from its effective price.
//
// PERCOLATOR_V16_TRADE_STEPS (600) and PERCOLATOR_V16_TRADE_SEEDS (2) size it; a run is replayed from the seed it prints
// (percolator-v16-helpers.ts). It prints per-instruction success shares and what the walk produced: legs settled by a
// later instruction, funding accruals with open interest, PnL changes, certificates written, certificates whose equity
// a haircut lowered, source claims, lifecycle changes with open legs.
