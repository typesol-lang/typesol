/** One change to a trade: a data byte, a signer dropped, two positions swapped or repeated. */
function mutate(w: World, rng: Rng, t: Instruction): Instruction {
  const accounts = t.accounts ?? [];
  if (rng.chance(50)) {
    const data = Buffer.from(t.data ?? new Uint8Array());
    data[1 + rng.int(data.length - 1)] = rng.int(256);
    return { ...t, data: new Uint8Array(data) };
  }
  const at = rng.int(accounts.length);
  const from = accounts[rng.int(accounts.length)]!;
  const k = rng.int(3);
  if (k === 0) return withAccount(w, t, at, from.address, accounts[at]!.role);
  if (k === 1) return withAccount(w, t, at, accounts[at]!.address, AccountRole.READONLY);
  return { ...t, accounts: accounts.slice(0, rng.int(accounts.length)) };
}

