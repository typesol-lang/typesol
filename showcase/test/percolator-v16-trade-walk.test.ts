function i128At(b: Buffer, at: number): bigint {
  return BigInt.asIntN(128, b.readBigUInt64LE(at) | (b.readBigUInt64LE(at + 8) << 64n));
}
function u128At(b: Buffer, at: number): bigint {
  return b.readBigUInt64LE(at) | (b.readBigUInt64LE(at + 8) << 64n);
}

/** A portfolio's signed position on `asset` (0 for none) in the reference. */
function position(w: World, p: Address, asset: number): bigint {
  const b = w.d.data(p);
  if (b.length < 9555) return 0n;
  for (let i = 0; i < 16; i++) {
    if (b[leg(i, "active")] !== 1 || b.readUInt32LE(leg(i, "asset_index")) !== asset) continue;
    const q = i128At(b, leg(i, "basis_pos_q"));
    const abs = q < 0n ? -q : q;
    return b[leg(i, "side")] === 1 ? -abs : abs;
  }
  return 0n;
}

function effectivePrice(w: World, asset: number): bigint {
  return w.d.data(w.m.market).readBigUInt64LE(marketAt.engine(asset, "asset.effective_price"));
}

/** What the walk measures, from the reference's accounts before and after each success. */
interface Tally {
  settled: number;
  fundingAccruals: number;
  pnlChanges: number;
  certWrites: number;
  haircut: number;
  sourceClaims: number;
  lifecycleWithLegs: number;
  attaches: number;
  clears: number;
  flips: number;
}

function observe(w: World, before: Map<Address, Buffer>, marketBefore: Buffer, tag: number, t: Tally): void {
  const market = w.d.data(w.m.market);
  const fe = marketAt.group("funding_epoch");
  if (market.readBigUInt64LE(fe) > marketBefore.readBigUInt64LE(fe)) t.fundingAccruals++;
  for (const [p, b0] of before) {
    const b1 = w.d.data(p);
    if (b1.length < 9555 || b0.length < 9555) continue;
    for (let i = 0; i < 16; i++) {
      const was = b0[leg(i, "active")] === 1;
      const is = b1[leg(i, "active")] === 1;
      if (was && is && b0.readUInt32LE(leg(i, "asset_index")) === b1.readUInt32LE(leg(i, "asset_index"))) {
        const moved = i128At(b0, leg(i, "k_snap")) !== i128At(b1, leg(i, "k_snap")) || i128At(b0, leg(i, "f_snap")) !== i128At(b1, leg(i, "f_snap"));
        if (moved) t.settled++;
        if (b0[leg(i, "side")] !== b1[leg(i, "side")]) t.flips++;
      }
      if (!was && is) t.attaches++;
      if (was && !is) t.clears++;
    }
    const pnl = portfolioAt("pnl");
    if (i128At(b0, pnl) !== i128At(b1, pnl)) t.pnlChanges++;
    const certChanged = !b0.subarray(CERT, CERT + CERT_LEN).equals(b1.subarray(CERT, CERT + CERT_LEN));
    if (certChanged && b1[CERT + offsetOf("HealthCert", "valid")] === 1) {
      t.certWrites++;
      const equity = i128At(b1, CERT + offsetOf("HealthCert", "certified_equity"));
      const plain = BigInt(u128At(b1, portfolioAt("capital"))) + i128At(b1, pnl) + i128At(b1, portfolioAt("fee_credits"));
      if (equity < plain) t.haircut++;
    }
    if (u128At(b1, portfolioAt("source_domains") + offsetOf("PortfolioSourceDomain", "source_claim_bound_num")) !== 0n) t.sourceClaims++;
  }
  if (tag === 40) {
    const sp = marketAt.engine(1, "asset.stored_pos_count_long");
    if (marketBefore.readBigUInt64LE(sp) !== 0n || marketBefore.readBigUInt64LE(marketAt.engine(1, "asset.stored_pos_count_short")) !== 0n)
      t.lifecycleWithLegs++;
  }
}

/** A trade between two of the world's portfolios. */
/** A trade's size for portfolio `pa` on `asset`: its position closed or flipped, sizes across the scales, the cap. */
function sizeFor(w: World, rng: Rng, pa: Address, asset: number): bigint {
  const current = position(w, pa, asset);
  const r = rng.int(100);
  let size: bigint;
  if (r < 15 && current !== 0n) size = -current;
  else if (r < 25 && current !== 0n) size = -current * 2n;
  else if (r < 55) size = BigInt(1 + rng.int(1_000_000)) * 1_000_000n;
  else if (r < 80) size = BigInt(1 + rng.int(1_000_000)) * 10_000_000n;
  else if (r < 90) size = BigInt(1 + rng.int(1000));
  else if (r < 95) size = POSITION_CAP - BigInt(rng.int(3));
  else size = POSITION_CAP + BigInt(rng.int(3));
  if (r >= 25 && rng.chance(50)) size = -size;
  if (size === 0n) size = 1n;
  return size;
}

/** A print: mostly near the effective price, now and then at or past the bounds. */
function execFor(w: World, rng: Rng, asset: number): bigint {
  const effective = effectivePrice(w, asset);
  const e = rng.int(20);
  return e === 0
    ? 1n
    : e === 1
      ? MAX_ORACLE_PRICE
      : e === 2
        ? MAX_ORACLE_PRICE + 1n
        : e === 3
          ? 0n
          : (effective * BigInt(9_000 + rng.int(2_001))) / 10_000n || 1n;
}

/** A fee: the base, a little above, the maximum, past it, below the base. */
function feeFor(w: World, rng: Rng): bigint {
  const base = w.d.data(w.m.market).readBigUInt64LE(marketAt.wrapper("trade_fee_base_bps"));
  const f = rng.int(10);
  return f < 4 ? base : f < 7 ? base + BigInt(rng.int(20)) : f < 9 ? 500n : f === 9 && rng.chance(50) ? 501n : base === 0n ? 0n : base - 1n;
}

/** A pair of distinct portfolios. */
function pairOf(w: World, rng: Rng): [number, number] {
  const n = w.portfolios.length;
  const i = rng.int(n);
  let j = rng.int(n - 1);
  if (j >= i) j++;
  return [i, j];
}

function tradeIx(w: World, rng: Rng): { payer: KeyPairSigner; ix: Instruction } {
  const [i, j] = pairOf(w, rng);
  const [oa, ob, pa, pb] = [w.owners[i]!, w.owners[j]!, w.portfolios[i]!, w.portfolios[j]!];
  const asset = rng.int(3);
  const size = sizeFor(w, rng, pa, asset);
  const exec = execFor(w, rng, asset);
  const fee = feeFor(w, rng);
  const cap = rng.chance(90) ? rng.int(10_001) : 10_001;
  const ids = (p: Address) => (w.d.reference.getAccount(p).exists && w.d.data(p).length >= 9555 ? [w.d.portfolioId(p), w.d.positionEpoch(p)] : [1n, 0n]);
  const [aId, aEpoch] = ids(pa);
  const [bId, bEpoch] = ids(pb);
  return {
    payer: oa,
    ix: ix.tradeNoCpi(w.m, oa, ob, pa, pb, {
      aId,
      aEpoch: rng.chance(97) ? aEpoch! : aEpoch! + 1n,
      bId: bId!,
      bEpoch: bEpoch!,
      asset: rng.chance(98) ? asset : 3 + rng.int(2),
      marketId: rng.chance(98) ? w.marketId(asset) : w.marketId(asset) + 1n,
      size,
      exec,
      fee,
      cap,
    } as never),
  };
}

/** BatchTradeNoCpi between two portfolios: one to three legs on distinct assets (now and then a repeat or an asset out
 * of range), each sized, priced and charged as a single trade. */
function batchIx(w: World, rng: Rng): { payer: KeyPairSigner; ix: Instruction } {
  const [i, j] = pairOf(w, rng);
  const [pa, pb] = [w.portfolios[i]!, w.portfolios[j]!];
  const assets = [0, 1, 2].sort(() => (rng.chance(50) ? -1 : 1)).slice(0, 1 + rng.int(3));
  if (rng.chance(3)) assets.push(rng.chance(50) ? assets[0]! : 3 + rng.int(2));
  const ids = (p: Address) => (w.d.reference.getAccount(p).exists && w.d.data(p).length >= 9555 ? [w.d.portfolioId(p), w.d.positionEpoch(p)] : [1n, 0n]);
  const [aId, aEpoch] = ids(pa);
  const [bId, bEpoch] = ids(pb);
  return {
    payer: w.owners[i]!,
    ix: ix.batchTradeNoCpi(w.m, w.owners[i]!, w.owners[j]!, pa, pb, {
      aId: aId!,
      aEpoch: aEpoch!,
      bId: bId!,
      bEpoch: bEpoch!,
      // Most legs at the effective price and the base fee (each corrupted leg refuses the whole batch).
      legs: assets.map((asset) => ({
        asset,
        marketId: w.marketId(asset < 3 ? asset : 0),
        size: sizeFor(w, rng, pa, asset),
        exec: asset < 3 && rng.chance(75) ? effectivePrice(w, asset) : execFor(w, rng, asset < 3 ? asset : 0),
        fee: rng.chance(75) ? w.d.data(w.m.market).readBigUInt64LE(marketAt.wrapper("trade_fee_base_bps")) : feeFor(w, rng),
      })),
    }),
  };
}

/** TradeCpi or BatchTradeCpi of taker `i` against the LP through its auth matcher. */
function cpiIx(w: World, rng: Rng, i: number, lp: Trader, mt: Lp): { payer: KeyPairSigner; ix: Instruction; tag: number } {
  const pa = w.portfolios[i]!;
  const common = {
    aId: w.d.portfolioId(pa),
    aEpoch: w.d.positionEpoch(pa),
    bId: w.d.portfolioId(lp.portfolio),
    bEpoch: w.d.positionEpoch(lp.portfolio),
    bSequence: w.d.portfolioSequence(lp.portfolio),
  };
  if (rng.chance(60)) {
    const asset = rng.int(3);
    return {
      payer: w.owners[i]!,
      tag: 10,
      ix: ix.tradeCpi(w.m, w.owners[i]!, pa, lp.portfolio, mt, {
        ...common,
        asset,
        marketId: w.marketId(asset),
        size: sizeFor(w, rng, pa, asset),
        fee: feeFor(w, rng),
        limit: rng.chance(80) ? 0n : execFor(w, rng, asset),
        cap: rng.int(10_002),
      }),
    };
  }
  const assets = [0, 1, 2].sort(() => (rng.chance(50) ? -1 : 1)).slice(0, 1 + rng.int(3));
  return {
    payer: w.owners[i]!,
    tag: 67,
    ix: ix.batchTradeCpi(w.m, w.owners[i]!, pa, lp.portfolio, mt, {
      ...common,
      maxSlippage: rng.chance(80) ? (1n << 128n) - 1n : BigInt(rng.int(1_000_000)),
      maxFee: rng.chance(80) ? (1n << 128n) - 1n : BigInt(rng.int(1_000_000)),
      legs: assets.map((asset) => ({
        asset,
        marketId: w.marketId(asset),
        size: sizeFor(w, rng, pa, asset),
        fee: rng.chance(75) ? w.d.data(w.m.market).readBigUInt64LE(marketAt.wrapper("trade_fee_base_bps")) : feeFor(w, rng),
        limit: rng.chance(85) ? 0n : execFor(w, rng, asset),
      })),
    }),
  };
}

/** A valid trade of `size` on `asset` between portfolios `i` (long for a positive size) and `j`, at the effective price,
 * at the base fee. */
function tradeOf(w: World, i: number, j: number, asset: number, size: bigint): { payer: KeyPairSigner; ix: Instruction } {
  const [oa, ob, pa, pb] = [w.owners[i]!, w.owners[j]!, w.portfolios[i]!, w.portfolios[j]!];
  const base = w.d.data(w.m.market).readBigUInt64LE(marketAt.wrapper("trade_fee_base_bps"));
  return {
    payer: oa,
    ix: ix.tradeNoCpi(w.m, oa, ob, pa, pb, {
      aId: w.d.portfolioId(pa),
      aEpoch: w.d.positionEpoch(pa),
      bId: w.d.portfolioId(pb),
      bEpoch: w.d.positionEpoch(pb),
      asset,
      marketId: w.marketId(asset),
      size,
      exec: effectivePrice(w, asset),
      fee: base,
      cap: 10_000,
    }),
  };
}

